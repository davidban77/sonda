"""Contract tests for scripts/check_session_links.py.

Each case builds a throwaway git repository, makes real commits, and runs the
script as a subprocess with the environment the workflow gives it.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "check_session_links.py"

# Built from parts so this file reads the same to a reviewer and to a grep.
LINK = "https://" + "claude.ai/code/" + "session_01AbCdEfGhIjKlMnOpQrStUv"
SECRET_ID = "01AbCdEfGhIjKlMnOpQrStUv"


class SessionLinkCheck(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name)
        self.git("init", "-q", "-b", "main")
        self.git("config", "user.email", "test@example.invalid")
        self.git("config", "user.name", "test")
        self.base = self.commit("base: initial commit")

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def git(self, *args: str) -> str:
        return subprocess.run(
            ["git", *args], cwd=self.repo, check=True, capture_output=True, text=True
        ).stdout.strip()

    def commit(self, message: str) -> str:
        self.git("commit", "-q", "--allow-empty", "-m", message)
        return self.git("rev-parse", "HEAD")

    def run_check(self, **env: str) -> subprocess.CompletedProcess[str]:
        full = {k: v for k, v in os.environ.items() if not k.startswith(("PR_", "COMMIT_RANGE"))}
        full.update(env)
        return subprocess.run(
            [sys.executable, str(SCRIPT)], cwd=self.repo, env=full, capture_output=True, text=True
        )

    def event(self, pull_request: object) -> str:
        """Write an event payload the way Actions does and return its path."""
        path = self.repo / "event.json"
        path.write_text(json.dumps({"action": "opened", "pull_request": pull_request}))
        return str(path)

    def pr(self, head: str, title: str = "deps: bump x", body: str | None = "") -> subprocess.CompletedProcess[str]:
        return self.run_check(
            COMMIT_RANGE=f"{self.base}..{head}",
            PR_EVENT_PATH=self.event({"title": title, "body": body}),
        )

    # --- clean inputs pass, and say how much they scanned -----------------

    def test_clean_pull_request_passes_and_counts_what_it_scanned(self) -> None:
        self.commit("deps: bump a")
        head = self.commit("deps: bump b\n\nCo-Authored-By: someone <x@example.invalid>")
        r = self.pr(head, body="## What changed\n\nGenerated with Claude Code (https://claude.com/claude-code)")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("2 commit(s), the title and the body", r.stdout)

    def test_clean_push_passes(self) -> None:
        head = self.commit("ci: bump y (#1)")
        r = self.run_check(COMMIT_RANGE=f"{self.base}..{head}")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("1 commit(s)", r.stdout)

    # --- each place a link can hide is caught -----------------------------

    def test_trailer_in_a_pull_request_commit_fails(self) -> None:
        self.commit("deps: bump a")
        head = self.commit(f"deps: bump b\n\nClaude-Session: {LINK}")
        r = self.pr(head)
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn(f"commit {head[:12]} line 3", r.stdout)

    def test_link_in_pull_request_body_fails(self) -> None:
        head = self.commit("deps: bump a")
        r = self.pr(head, body=f"## What changed\n\n---\n_Generated by [Claude Code]({LINK})_")
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn("pull request body line 4", r.stdout)

    def test_link_in_pull_request_title_fails(self) -> None:
        head = self.commit("deps: bump a")
        r = self.pr(head, title=f"deps: bump a {LINK}")
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn("pull request title line 1", r.stdout)

    def test_link_in_a_pushed_squash_message_fails(self) -> None:
        head = self.commit(f"ci: bump y (#1)\n\n- y 1 -> 2\n\nClaude-Session: {LINK}")
        r = self.run_check(COMMIT_RANGE=f"{self.base}..{head}")
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)

    def test_match_is_case_insensitive(self) -> None:
        head = self.commit("deps: bump a\n\nsee HTTPS://CLAUDE.AI/CODE/SESSION_XYZ")
        self.assertEqual(self.pr(head).returncode, 1)

    def test_a_single_commit_range_is_scanned(self) -> None:
        head = self.commit(f"ci: x\n\nClaude-Session: {LINK}")
        r = self.run_check(COMMIT_RANGE=head)
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn("1 commit(s)", r.stdout)

    # --- the check does not repeat the leak -------------------------------

    def test_findings_redact_the_session_id(self) -> None:
        head = self.commit(f"deps: bump a\n\nClaude-Session: {LINK}")
        r = self.pr(head, body=LINK, title=f"deps: {LINK}")
        self.assertEqual(r.returncode, 1)
        self.assertGreaterEqual(r.stdout.count("session_<redacted>"), 3, r.stdout)
        self.assertNotIn(SECRET_ID, r.stdout + r.stderr)

    # --- vacuous or broken inputs are refused, not reported clean ---------

    def test_empty_range_is_refused(self) -> None:
        r = self.run_check(
            COMMIT_RANGE=f"{self.base}..{self.base}", PR_EVENT_PATH=self.event({"title": "t", "body": ""})
        )
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn("contains no commits", r.stderr)

    def test_missing_range_is_refused(self) -> None:
        r = self.run_check(PR_EVENT_PATH=self.event({"title": "t", "body": ""}))
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)

    def test_unreadable_range_is_refused(self) -> None:
        r = self.run_check(COMMIT_RANGE="deadbeef..cafebabe")
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)

    def test_empty_title_in_pr_mode_is_refused(self) -> None:
        head = self.commit("deps: bump a")
        r = self.pr(head, title="  ")
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn("title is empty", r.stderr)

    def test_missing_event_payload_is_refused(self) -> None:
        head = self.commit("deps: bump a")
        r = self.run_check(COMMIT_RANGE=f"{self.base}..{head}", PR_EVENT_PATH=str(self.repo / "nope.json"))
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn("cannot read the event payload", r.stderr)

    def test_payload_without_a_pull_request_is_refused(self) -> None:
        head = self.commit("deps: bump a")
        path = self.repo / "push-event.json"
        path.write_text(json.dumps({"ref": "refs/heads/main"}))
        r = self.run_check(COMMIT_RANGE=f"{self.base}..{head}", PR_EVENT_PATH=str(path))
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn("no pull_request object", r.stderr)

    def test_null_body_is_a_pull_request_with_no_body(self) -> None:
        head = self.commit("deps: bump a")
        r = self.pr(head, body=None)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    # --- the text never travels through the environment -------------------

    def test_title_and_body_are_not_read_from_the_environment(self) -> None:
        # The old interface: a link here must be ignored, because the workflow
        # no longer sets these and a stray value must not be mistaken for input.
        head = self.commit("deps: bump a")
        r = self.run_check(
            COMMIT_RANGE=f"{self.base}..{head}",
            PR_EVENT_PATH=self.event({"title": "deps: bump a", "body": "clean"}),
            PR_TITLE=LINK, PR_BODY=LINK,
        )
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)


if __name__ == "__main__":
    unittest.main()
